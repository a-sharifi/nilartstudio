 await page.getByLabel("Total incoming value (toman)",{exact:true}).fill("1000")
 await page.getByLabel("Reason and count reference",{exact:true}).fill("Synthetic counted demo stock")
 await page.getByRole("button",{name:"Confirm and record movement",exact:true}).click()
 await expect(page).toHaveURL(/\/inventory\/positions\/[0-9a-f-]{36}$/)
 await expect(page.getByText("Total value / average cost (toman): 1000.000000 / 4.000000",{exact:true})).toBeVisible()
 await page.reload()
