 await page.reload()
 await expect(page.getByLabel("English business name",{exact:true})).toHaveValue(label)
 const material=randomUUID(),code=`DEMO-${material.slice(0,8).toUpperCase()}`
 const saved=await write(`/api/v1/admin/costing/resources/${material}/versions/${randomUUID()}`,{expected_version:0,content:{kind:"material",code,title_fa:"کاغذ آزمایش مرورگر",title_en:"Browser demo paper",base_unit:"sheet",purchase_unit:"pack",purchase_to_base:"250",supplier:"Synthetic demo supplier",rate:{amount:"4",currency:"IRT"}},reason:"Synthetic material for isolated browser test"})
