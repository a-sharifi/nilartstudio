import {expect,test} from "@playwright/test"
test("saved basket uses reference rows and persists quantities, edits, remove and undo",async({page})=>{
 await page.goto("/en/cart")
 await expect(page.getByRole("heading",{name:"Your cart is empty.",exact:true})).toBeVisible()
 await expect(page.getByRole("button",{name:"Load a demo cart"})).toHaveCount(0)
 await page.goto("/en/products/cats-sketchbook-127gsm")
 await page.getByRole("radio",{name:/A4/}).click()
 await page.getByRole("radio",{name:/50/}).click()
 await page.getByRole("radio",{name:/3 mm|3mm/}).click()
 await page.getByRole("button",{name:"Add to basket",exact:true}).click()
 await expect(page.getByText("Added to your basket.",{exact:false})).toBeVisible()
 await page.goto("/en/cart")
 await expect(page.locator(".cart-row")).toHaveCount(1)
 await expect(page.locator(".cart-options")).toContainText("A4")
 await expect(page.locator(".cart-summary-total")).toContainText("245,000")
 await expect(page.locator(".cart-checkout-button")).toBeDisabled()
 await expect(page.locator("#cart-coupon-input")).toBeDisabled()
 await page.getByRole("button",{name:/Increase quantity of/}).click()
 await expect(page.locator(".cart-summary-total")).toContainText("490,000")
 await page.reload()
 await expect(page.locator(".cart-summary-total")).toContainText("490,000")
 await page.getByRole("button",{name:"Edit options",exact:true}).click()
 await expect(page).toHaveURL(/basketLine=/)
 await expect(page.getByRole("radio",{name:/A4/})).toBeChecked()
 await expect(page.locator("#published-product-quantity")).toHaveValue("2")
 await page.getByRole("radio",{name:/A5/}).click()
 await page.getByRole("radio",{name:/50/}).click()
 await page.getByRole("radio",{name:/3 mm|3mm/}).click()
 await page.getByRole("button",{name:"Save selections",exact:true}).click()
 await expect(page).toHaveURL(/\/en\/cart$/)
 await expect(page.locator(".cart-summary-total")).toContainText("410,000")
 await page.getByRole("button",{name:/Remove from cart:/}).click()
 await expect(page.getByRole("heading",{name:"Your cart is empty.",exact:true})).toBeVisible()
 await page.getByRole("button",{name:"Undo",exact:true}).click()
 await expect(page.locator(".cart-row")).toHaveCount(1)
 await expect(page.locator(".cart-summary-total")).toContainText("410,000")
 await page.setViewportSize({width:390,height:844})
 await page.goto("/fa/cart")
 await expect(page.locator(".cart-row")).toHaveCount(1)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()
 await page.screenshot({path:"/tmp/nilart-basket-mobile.png",fullPage:true})
})

test("selected bundles and framed artworks join the same saved basket",async({page})=>{
 await page.goto("/en/bundles/cats-bundle")
 await page.getByRole("radio",{name:/A4/}).click()
 await page.getByRole("radio",{name:/50/}).click()
 await page.getByRole("radio",{name:/3 mm|3mm/}).click()
 await page.getByRole("button",{name:"Add bundle to basket",exact:true}).click()
 await expect(page.getByText("Added to your basket.",{exact:false})).toBeVisible()
 await page.goto("/en/artworks/afternoon")
 await page.locator('input[name="art-frame"]').nth(1).check()
 await page.getByRole("button",{name:"Add to basket",exact:true}).click()
 await expect(page.getByText("Added to your basket.",{exact:false})).toBeVisible()
 await page.goto("/en/cart")
 await expect(page.locator(".cart-row")).toHaveCount(2)
 await expect(page.locator(".cart-summary-total")).toContainText("4,865,000")
 await page.getByRole("button",{name:"Edit bundle",exact:true}).click()
 await expect(page.getByRole("radio",{name:/A4/})).toBeChecked()
 await page.getByRole("radio",{name:/A5/}).click()
 await page.getByRole("radio",{name:/50/}).click()
 await page.getByRole("radio",{name:/3 mm|3mm/}).click()
 await page.getByRole("button",{name:"Save selections",exact:true}).click()
 await expect(page).toHaveURL(/\/en\/cart$/)
 await expect(page.locator(".cart-summary-total")).toContainText("4,825,000")
 await page.setViewportSize({width:979,height:900})
 await page.screenshot({path:"/tmp/nilart-basket-desktop.png",fullPage:true})
})
