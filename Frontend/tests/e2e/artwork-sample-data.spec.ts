import {expect,test} from "@playwright/test"
test("database artwork samples have price, stock, artist, specifications and downloaded images",async({page,request})=>{
 const response=await request.get("/api/v1/catalog/artworks?page_size=100")
 const data=await response.json()
 expect(data.items).toHaveLength(9)
 for(const item of data.items){
  expect(item.details.stock).toBe(1)
  expect(item.details.artist_fa).toBe("نیلوفر مرادی")
  expect(Number(item.details.price_amount)).toBeGreaterThan(0)
  expect(item.details.medium).toBe("colored-pencil")
  expect((await request.get(item.details.image_url)).ok()).toBeTruthy()
 }
 await page.goto("/fa/artworks")
 const cards=page.locator("article.art-card")
 await expect(cards).toHaveCount(6)
 for(const card of await cards.all()){
  await expect(card.locator(".art-artist")).toHaveText("نیلوفر مرادی")
  await expect(card.locator(".art-card-status")).toContainText("موجود")
  await expect(card.locator(".art-specs")).toContainText("مدادرنگی")
  await expect(card.locator("img")).toBeVisible()
  await expect.poll(()=>card.locator("img").evaluate((img:HTMLImageElement)=>img.complete&&img.naturalWidth>0)).toBeTruthy()
 }
 await page.getByRole("button",{name:"بعدی",exact:true}).click()
 await expect(cards).toHaveCount(3)
 for(const card of await cards.all())await expect(card.locator(".art-artist")).toHaveText("نیلوفر مرادی")
 await page.goto("/fa/artworks")
 await expect(cards).toHaveCount(6)
 await page.setViewportSize({width:979,height:900})
 await cards.first().scrollIntoViewIfNeeded()
 await page.screenshot({path:"/tmp/nilart-artworks-populated.png"})
 await page.goto("/fa/artworks/afternoon")
 await expect(page.locator(".ad-byline")).toHaveText("نیلوفر مرادی")
 await expect(page.locator(".ad-stock")).toContainText("موجود")
 await expect(page.locator(".ad-main-image img")).toBeVisible()
 await expect(page.locator(".ad-gallery-note")).toContainText("تصویر نمونه")
 await page.goto("/en/artworks?medium=colored-pencil&available=1")
 await expect(page.locator("article.art-card")).toHaveCount(6)
 await expect(page.locator(".art-artist").first()).toHaveText("Niloufar Moradi")
})

test("all artwork details display persisted surface and frame labels",async({page,request})=>{
 const data=await (await request.get("/api/v1/catalog/artworks?page_size=100")).json()
 for(const work of data.items){
  expect(work.details.surface_fa).toBe("کاغذ طراحی ۳۰۰ گرم — نمونه")
  expect(work.details.frame_fa).toBe("بدون قاب — نمونه")
  await page.goto(`/fa/artworks/${work.slug}`)
  await expect(page.locator(".ad-key-specs > div").nth(1).locator("dd")).toHaveText(work.details.surface_fa)
  await expect(page.locator(".ad-key-specs > div").nth(3).locator("dd")).toHaveText(work.details.frame_fa)
  await expect(page.locator(".ad-spec-table")).toContainText(work.details.surface_fa)
  await page.locator('input[name="art-frame"]').nth(1).check()
  await expect(page.locator(".ad-key-specs > div").nth(3).locator("dd")).toHaveText("با قاب چوبی — نمونه")
  await expect(page.locator(".ad-price-block strong")).toContainText((Number(work.details.price_amount)+650000).toLocaleString("fa-IR"))
  await page.locator('input[name="art-frame"]').first().check()
  await expect(page.locator(".ad-price-block strong")).toContainText(Number(work.details.price_amount).toLocaleString("fa-IR"))
 }
 await page.goto("/en/artworks/afternoon")
 await expect(page.locator(".ad-key-specs")).toContainText("300 gsm drawing paper — sample")
 await expect(page.locator(".ad-key-specs")).toContainText("Unframed — sample")
})
