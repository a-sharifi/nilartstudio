import {expect,test,type Page} from "@playwright/test"
const id="00000000-0000-4000-8000-000000000001",older="00000000-0000-4000-8000-000000000002"
async function setup(page:Page,allowed=true){
 await page.route("**/api/v1/auth/access",r=>r.fulfill({json:{account_id:id,roles:["admin"],permissions:allowed?["identity.manage"]:["orders.read_all"]}}))
 const requests:URLSearchParams[]=[]
 await page.route("**/api/v1/admin/identity/audits?*",r=>{const q=new URL(r.request().url()).searchParams;requests.push(q);return r.fulfill({json:{items:q.get("q")==="missing"?[]:[{id:q.has("cursor")?older:id,actor_id:q.has("cursor")?null:id,account_id:id,action:"access.updated",reason:q.has("cursor")?"Previous access review":"Assigned support responsibilities",created_at:"2026-10-14T10:00:00Z"}],next_cursor:q.has("cursor")||q.get("q")==="missing"?null:id}})})
 return requests
}
test("activity filters on the server, paginates and validates account IDs",async({page})=>{
 const requests=await setup(page);await page.goto("/en/admin/activity")
 await expect(page.getByText("Assigned support responsibilities",{exact:true})).toBeVisible()
 await page.getByRole("button",{name:"Older activity",exact:true}).click()
 await expect(page.getByText("Previous access review",{exact:true})).toBeVisible()
 expect(requests.at(-1)?.get("cursor")).toBe(id)
 await page.getByLabel("Account ID",{exact:true}).fill("bad")
 await page.getByRole("button",{name:"Search",exact:true}).click()
 await expect(page.getByRole("main").getByRole("alert")).toHaveText("Enter a valid account ID.")
 await page.getByLabel("Account ID",{exact:true}).fill(id)
 await page.getByLabel("Actor ID",{exact:true}).fill("bad")
 await page.getByRole("button",{name:"Search",exact:true}).click()
 await expect(page.getByRole("main").getByRole("alert")).toHaveText("Enter a valid actor ID.")
 await page.getByLabel("Actor ID",{exact:true}).fill(id)
 await page.getByLabel("Search action or reason",{exact:true}).fill("missing")
 await page.getByRole("button",{name:"Search",exact:true}).click()
 await expect(page.getByText("No activity matches these filters.",{exact:true})).toBeVisible()
 expect(requests.at(-1)?.get("actor_id")).toBe(id);expect(requests.at(-1)?.get("account_id")).toBe(id);expect(requests.at(-1)?.has("cursor")).toBeFalsy()
 await page.getByRole("button",{name:"Clear filters",exact:true}).click()
 await expect(page.getByText("Assigned support responsibilities",{exact:true})).toBeVisible()
 expect(requests.at(-1)?.has("q")).toBeFalsy();expect(requests.at(-1)?.has("actor_id")).toBeFalsy()
})
test("order readers cannot request the private account activity log",async({page})=>{const requests=await setup(page,false);await page.goto("/en/admin/activity");await expect(page.getByText("Assigned support responsibilities",{exact:true})).toHaveCount(0);await expect(page.getByRole("heading",{name:/access|permission/i})).toBeVisible();expect(requests).toHaveLength(0)})
test("Persian activity page stays within a mobile viewport",async({page})=>{await setup(page);await page.setViewportSize({width:390,height:844});await page.goto("/fa/admin/activity");await expect(page.getByText("Assigned support responsibilities",{exact:true})).toBeVisible();expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy()})
test("activity read failure can be retried without a false empty state",async({page})=>{await setup(page);let failed=true;await page.route("**/api/v1/admin/identity/audits?*",r=>{if(!failed)return r.fallback();return r.fulfill({status:503,json:{code:"unavailable"}})});await page.goto("/en/admin/activity");await expect(page.getByRole("main").getByRole("alert")).toHaveText("Unable to load activity log.");await expect(page.getByText("No activity matches these filters.",{exact:true})).toHaveCount(0);failed=false;await page.getByRole("button",{name:"Reload activity",exact:true}).click();await expect(page.getByText("Assigned support responsibilities",{exact:true})).toBeVisible()})

test("date filters combine with actor and survive pagination until cleared",async({page})=>{
 const requests=await setup(page);await page.goto("/en/admin/activity")
 await expect(page.getByText("Assigned support responsibilities",{exact:true})).toBeVisible()
 await page.getByLabel("From date (Tehran)",{exact:true}).fill("2026-10-17")
 await page.getByLabel("To date (Tehran)",{exact:true}).fill("2026-10-16")
 await page.getByRole("button",{name:"Search",exact:true}).click()
 await expect(page.getByRole("main").getByRole("alert")).toHaveText("Start date must be on or before end date.")
 await page.getByLabel("From date (Tehran)",{exact:true}).fill("2026-10-16")
 await page.getByLabel("Actor ID",{exact:true}).fill(id)
 await page.getByRole("button",{name:"Search",exact:true}).click()
 await expect.poll(()=>requests.at(-1)?.get("date_from")).toBe("2026-10-16")
 expect(requests.at(-1)?.get("date_to")).toBe("2026-10-16")
 await page.getByRole("button",{name:"Older activity",exact:true}).click()
 await expect(page.getByText("Previous access review",{exact:true})).toBeVisible()
 expect(requests.at(-1)?.get("actor_id")).toBe(id);expect(requests.at(-1)?.get("date_to")).toBe("2026-10-16")
 await page.getByRole("button",{name:"Clear filters",exact:true}).click()
 await expect.poll(()=>requests.at(-1)?.has("date_from")).toBeFalsy()
 await expect(page.getByLabel("To date (Tehran)",{exact:true})).toHaveValue("")
})
test("exact action selection applies on search and stays scoped for older entries",async({page})=>{
 const requests=await setup(page);await page.goto("/en/admin/activity")
 await expect(page.getByText("Assigned support responsibilities",{exact:true})).toBeVisible()
 await page.getByRole("combobox",{name:"Action type",exact:true}).click()
 await page.getByRole("option",{name:"Access change",exact:true}).click()
 expect(requests.at(-1)?.has("action")).toBeFalsy()
 await page.getByRole("button",{name:"Search",exact:true}).click()
 await expect.poll(()=>requests.at(-1)?.get("action")).toBe("access.updated")
 await page.getByRole("button",{name:"Older activity",exact:true}).click()
 await expect(page.getByText("Previous access review",{exact:true})).toBeVisible()
 expect(requests.at(-1)?.get("action")).toBe("access.updated")
 await page.getByRole("button",{name:"Clear filters",exact:true}).click()
 await expect.poll(()=>requests.at(-1)?.has("action")).toBeFalsy()
 await expect(page.getByRole("combobox",{name:"Action type",exact:true})).toHaveValue("All actions")
})
