 await page.getByRole("button",{name:"Keep editing"}).click()
 await page.getByRole("button",{name:"Save option draft"}).click()
 await expect(page.getByText("Option draft saved and audited.",{exact:true})).toBeVisible()
 expect(writes).toBe(1);expect(csrf).toBe("fresh-test-csrf");expect(payload).toMatchObject({version:1,options:[{title_en:"Paper size"}]})
 await page.goto(`/en/admin/products/${product}/variants`)
 await expect(page.getByLabel("Option English title")).toHaveValue("Paper size")
