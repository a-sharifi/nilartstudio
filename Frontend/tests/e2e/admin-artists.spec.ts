test("account-status filter keeps artist and phone filters",async({page})=>{
 const record={id,phone:"+989123456789",phone_verified:true,blocked:false,version:0,roles:["artist"],overrides:{},permissions:[]};const requests:URL[]=[]
 await page.route("**/api/v1/auth/access",r=>r.fulfill({json:{account_id:owner,roles:["admin"],permissions:["identity.manage"]}}))
 await page.route("**/api/v1/admin/identity/**",r=>{
 const url=new URL(r.request().url())
 if(url.pathname.endsWith("/permissions"))return r.fulfill({json:[]})
 requests.push(url);return r.fulfill({json:{items:url.searchParams.get("blocked")==="true"?[]:[record],next_cursor:null}})
 })
 await page.goto("/en/admin/artists")
 await page.getByRole("button",{name:"Edit access"}).waitFor()
 await page.getByRole("combobox",{name:"Account status"}).click()
 await page.getByRole("option",{name:"Restricted",exact:true}).click()
 await expect(page.getByText("No accounts found.",{exact:true})).toBeVisible()
 expect(requests.at(-1)?.searchParams.get("blocked")).toBe("true")
 await page.getByLabel("Search phone number").fill("0912")
 await page.getByRole("button",{name:"Search",exact:true}).click()
 await expect.poll(()=>requests.at(-1)?.searchParams.get("q")).toBe("0912")
 expect(requests.at(-1)?.searchParams.get("role")).toBe("artist")
 expect(requests.at(-1)?.searchParams.get("blocked")).toBe("true")
 await page.getByRole("combobox",{name:"Account status"}).click()
 await page.getByRole("option",{name:"Active",exact:true}).click()
 await expect(page.getByRole("button",{name:"Edit access"})).toBeVisible()
 expect(requests.at(-1)?.searchParams.get("blocked")).toBe("false")
})
