test("directory phone search preserves artist scope and protects edited access",async({page})=>{
 const record={id,phone:"+989123456789",phone_verified:true,blocked:false,version:0,roles:["artist"],overrides:{},permissions:[]};const requests:URL[]=[]
 await page.route("**/api/v1/auth/access",r=>r.fulfill({json:{account_id:owner,roles:["admin"],permissions:["identity.manage"]}}))
 await page.route("**/api/v1/admin/identity/**",r=>{
 const url=new URL(r.request().url())
 if(url.pathname.endsWith("/permissions")||url.pathname.endsWith("/audits"))return r.fulfill({json:[]})
 requests.push(url);return r.fulfill({json:{items:url.searchParams.get("q")==="999000"?[]:[record],next_cursor:null}})
 })
 await page.goto("/en/admin/artists")
 await page.getByRole("button",{name:"Edit access"}).click()
 await page.getByLabel("Reason for change").fill("Unsaved access reason")
 await page.getByLabel("Search phone number").fill("999000")
 await page.getByRole("button",{name:"Search",exact:true}).click()
 await expect(page.getByRole("dialog")).toBeVisible()
 await page.getByRole("button",{name:"Keep editing"}).click()
 await expect(page.getByLabel("Reason for change")).toHaveValue("Unsaved access reason")
 await page.getByRole("button",{name:"Search",exact:true}).click()
 await page.getByRole("button",{name:"Discard changes"}).click()
 await expect(page.getByText("No accounts found.",{exact:true})).toBeVisible()
 expect(requests.at(-1)?.searchParams.get("role")).toBe("artist")
 expect(requests.at(-1)?.searchParams.get("q")).toBe("999000")
 await expect(page.getByLabel("Reason for change")).toHaveCount(0)
 await page.getByRole("button",{name:"Clear search"}).click()
 await expect(page.getByRole("button",{name:"Edit access"})).toBeVisible()
 expect(requests.at(-1)?.searchParams.get("q")).toBeNull()
})

